def main() -> int:
    if not STRINGS_H.exists():
        raise SystemExit(f"Missing {STRINGS_H}")

    chars = extract_chars(STRINGS_H.read_text(encoding="utf-8"))
    if not chars:
        raise SystemExit("No Chinese characters found in boat_strings.h")

    font_path = find_font()
    font = ImageFont.truetype(str(font_path), GLYPH_H)
    print(f"Font: {font_path}")
    print(f"Characters: {len(chars)}")

    row_lines: list[str] = []
    for ch in chars:
        rows = render_glyph(font, ch)
        byte_values = []
        for value in rows:
            byte_values.append(f"0x{(value >> 8) & 0xFF:02X}")
            byte_values.append(f"0x{value & 0xFF:02X}")
        row_lines.append(
            "    {0x%04X, {%s}}," % (ord(ch), ",".join(byte_values))
        )

    OUT_H.write_text(HEADER_TEMPLATE, encoding="utf-8")
    OUT_C.write_text(SOURCE_TEMPLATE.replace("__ROWS__", "\n".join(row_lines)),
                     encoding="utf-8")

    print(f"Wrote {OUT_H.relative_to(ROOT)}")
    print(f"Wrote {OUT_C.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
