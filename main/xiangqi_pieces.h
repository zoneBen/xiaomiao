// 根据棋子类型和颜色获取位图
static inline const uint8_t* xiangqi_get_piece_bitmap(XiangqiPieceType type, XiangqiColor color)
{
    if (type == XIANGQI_PIECE_NONE) return NULL;

    if (color == XIANGQI_COLOR_RED) {
        if (type <= XIANGQI_PIECE_PAWN) {
            return xiangqi_red_pieces[type];
        }
    } else if (color == XIANGQI_COLOR_BLACK) {
        if (type >= XIANGQI_PIECE_KING_B && type <= XIANGQI_PIECE_PAWN_B) {
            return xiangqi_black_pieces[type - XIANGQI_PIECE_KING_B];
        }
    }
    return NULL;
}

